function isoDay(baseDate: Date, offsetDays: number): string {
  const d = new Date(baseDate.getTime() + offsetDays * 86_400_000);
  return d.toISOString().slice(0, 10);
}

function isoDateTime(baseDate: Date, offsetHours: number): string {
  return new Date(baseDate.getTime() + offsetHours * 3_600_000).toISOString();
}

