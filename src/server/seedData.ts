export function reconcileBookCounts(state: LibraryDbState, bookId: number): void {
  const book = state.books.find((b) => b.book_id === bookId);
  if (!book) return;
  const bookCopies = state.copies.filter((c) => c.book_id === bookId);
  book.total_copies = bookCopies.length;
  book.available_copies = bookCopies.filter((c) => c.status === 'Available').length;
  book.issued_copies = bookCopies.filter((c) => c.status === 'Issued').length;
  book.reserved_copies = bookCopies.filter((c) => c.status === 'Reserved').length;
  book.unavailable_copies = bookCopies.filter(
    (c) =>
      c.status === 'Lost' ||
      c.status === 'Damaged' ||
      c.status === 'Under Repair' ||
      c.status === 'Retired'
  ).length;
}

export function reconcileBookRatings(state: LibraryDbState, bookId: number): void {
  const book = state.books.find((b) => b.book_id === bookId);
  if (!book) return;
  const reviews = state.reviews.filter((r) => r.book_id === bookId);
  book.rating_count = reviews.length;
  book.review_count = reviews.filter((r) => r.review.trim().length > 0).length;
  if (reviews.length === 0) {
    book.rating_average = 0;
  } else {
    const sum = reviews.reduce((acc, r) => acc + r.rating, 0);
    book.rating_average = Number((sum / reviews.length).toFixed(1));
  }
}

export function reconcileAllBookCounts(state: LibraryDbState): void {
  for (const book of state.books) {
    reconcileBookCounts(state, book.book_id);
  }
}

